#!/usr/bin/env python3
# Sizes of the kernel symbols that have no TzD definition (task #42).
#
# cc1tzd bounds `extern T x[]` by the symbol __tzd_size.x, which the unit
# defining x publishes.  Symbols defined by the linker script (__initcall0_start,
# _etext, __start___ex_table) or by assembly (init_top_pgt) have no such
# unit.  This script writes an assembly file that defines them:
#   tzd_sizes.py zero <vmlinux.o> <out.S> [obj...]
#       every undefined __tzd_size.X as 0 (first link, to get addresses);
#   tzd_sizes.py real <vmlinux.o> <vmlinux> <out.S> [obj...]
#       the ELF size of X when it has one (assembly with .size), otherwise
#       the bytes from X to the end of the output section holding it (a
#       linker-script boundary: the region it starts), 0 at a section end.
# Each size is an 8-byte constant in .rodata, as a TzD unit publishes it.
# Both passes write the same entries, so a relink with the real values
# gives the same addresses.  [obj...] are the objects
# linked beside vmlinux.o (init/version-timestamp.o): what they define is
# not written.
#
# Symbols in regions.list (next to this script) get the region stated
# there instead (task #75).
#
# It also defines the symbols of missing.list (next to this script): those
# the kernel refers to only from code that GCC removes and that TzD keeps
# (its checks and wipes are side effects).  Each becomes a stub that stops
# the kernel (tzd_trap) when it is called; its size is 0, so any access
# through it traps too.  Any other undefined symbol still fails the link.
import os
import subprocess
import sys

MISSING = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "missing.list")
REGIONS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "regions.list")


def undefined(obj):
    out = subprocess.run(["nm", "-u", obj], capture_output=True, text=True,
                         check=True).stdout
    return {line.split()[-1] for line in out.splitlines() if line.split()}


def defined(obj):
    out = subprocess.run(["nm", "--defined-only", obj], capture_output=True,
                         text=True, check=True).stdout
    return {line.split()[-1] for line in out.splitlines() if line.split()}


def previous(path):
    names, stubs = [], []
    with open(path) as f:
        for line in f:
            p = line.split()
            if len(p) == 2 and p[0] == ".globl" and p[1].startswith("__tzd_size."):
                names.append(p[1][len("__tzd_size."):])
            elif len(p) == 3 and p[0] == ".type" and p[2] == "@function":
                stubs.append(p[1].rstrip(","))
    return names, stubs


def undefined_sizes(undef):
    return sorted(n[len("__tzd_size."):] for n in undef
                  if n.startswith("__tzd_size."))


def missing_list():
    names = set()
    with open(MISSING) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                names.add(line)
    return names


def regions_list():
    regions = {}
    with open(REGIONS) as f:
        for line in f:
            p = line.split("#", 1)[0].split()
            if not p:
                continue
            if len(p) != 3:
                sys.exit(f"tzd_sizes: bad regions.list line: {line.strip()}")
            regions[p[0]] = (p[1], p[2])
    return regions


def symbols(elf):
    out = subprocess.run(["nm", "-S", elf], capture_output=True, text=True,
                         check=True).stdout
    syms = {}
    for line in out.splitlines():
        p = line.split()
        if len(p) == 4:
            syms[p[3]] = (int(p[0], 16), int(p[1], 16))
        elif len(p) == 3:
            syms[p[2]] = (int(p[0], 16), 0)
    return syms


def sections(elf):
    out = subprocess.run(["readelf", "-SW", elf], capture_output=True,
                         text=True, check=True).stdout
    secs = []
    for line in out.splitlines():
        line = line.replace("[ ", "[")
        p = line.split()
        if len(p) >= 7 and p[0].startswith("[") and p[0] != "[Nr]":
            try:
                addr, size = int(p[3], 16), int(p[5], 16)
            except ValueError:
                continue
            if addr and size:
                secs.append((addr, addr + size))
    return secs


def write(path, sizes, stubs):
    with open(path, "w") as f:
        f.write("/* Generated by tests/kernel/tzd_sizes.py (task #42). */\n")
        # Constants in memory, as a TzD unit defines them (cc1tzd loads
        # the size from __tzd_size.X).
        f.write("\t.pushsection .rodata\n\t.balign 8\n")
        for name, size in sizes:
            f.write(f"\t.globl __tzd_size.{name}\n")
            f.write(f"__tzd_size.{name}:\n\t.quad {size}\n")
        f.write("\t.popsection\n")
        for i, name in enumerate(stubs):
            msg = f"tzd: {name} is not in this kernel (tests/kernel/missing.list)\\n"
            f.write("\t.pushsection .rodata.tzd_missing,\"a\"\n")
            f.write(f".Ltzd_missing_{i}:\n\t.asciz \"{msg}\"\n\t.popsection\n")
            f.write("\t.pushsection .text\n")
            f.write(f"\t.globl {name}\n\t.type {name}, @function\n{name}:\n")
            f.write(f"\tleaq .Ltzd_missing_{i}(%rip), %rdi\n"
                    "\tcall tzd_trap\n\tud2\n")
            f.write(f"\t.size {name}, 0\n\t.popsection\n")


def main():
    mode = sys.argv[1]
    if mode == "zero":
        undef = undefined(sys.argv[2])
        for obj in sys.argv[4:]:
            undef -= defined(obj)
        names = undefined_sizes(undef)
        stubs = sorted(undef & missing_list())
    else:
        # vmlinux.o now holds the zero values (kc2d.a): the names are
        # those the zero pass wrote.
        names, stubs = previous(sys.argv[4])
    if mode == "zero":
        write(sys.argv[3], [(n, 0) for n in names], stubs)
        return
    syms, secs = symbols(sys.argv[3]), sections(sys.argv[3])
    regions = regions_list()
    for n, ends in regions.items():
        for e in (n,) + ends:
            if e not in syms:
                sys.exit(f"tzd_sizes: regions.list: {e} is not in the kernel")
    sizes = []
    for n in names:
        if n not in syms:
            sys.exit(f"tzd_sizes: {n} is not defined in the kernel")
        addr, size = syms[n]
        if n in stubs:
            size = 0
        elif n in regions:
            lo, hi = syms[regions[n][0]][0], syms[regions[n][1]][0]
            if hi < lo:
                sys.exit(f"tzd_sizes: regions.list: {n} ends before it starts")
            size = hi - lo
        elif size == 0:
            for lo, hi in secs:
                if lo <= addr < hi:
                    size = hi - addr
                    break
        sizes.append((n, size))
    write(sys.argv[4], sizes, stubs)


main()
